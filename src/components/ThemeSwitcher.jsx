function ThemeButton({icon}) {
  return (
    <button className="theme-switcher__button">
      <div>
        {icon}
      </div>
    </button>
  );
}
export default function ThemeSwitcher() {
  const theme = useSelector(({ appSettings }) => appSettings.theme);
  const dispatch = useDispatch();

  const themeIcons = {
    'light': <SunIcon />,
    'dark': <MoonIcon />,
    'system': <SystemSettingsIcon />,
  }
  const themesList = Object.keys(themeIcons);

  const themeList = (
    <ul>
      {themesList.map((item, i) => (
        <li key={i + item[0]}>
          <button onClick={() => dispatch(handleSetTheme(item))}>
            <div>{themeIcons[item]}</div>
            <p>{wordToRegularCase(item)}</p>
          </button>
        </li>
      ))}
    </ul>
  );
  
  return (
    <Dropdown 
      dropdownBtn={<ThemeButton icon={themeIcons[theme]} />}
      dropdownStyles="dropdown theme-switcher"
      dropdownContentStyles="dropdown-styles-1"
      dropdownType='click'
      >
        {themeList}
    </Dropdown>
  );
}